from __future__ import annotations

import os
import requests
import pandas as pd
import streamlit as st

DEFAULT_API_URL = os.getenv("FORECAST_API_URL", "http://127.0.0.1:8000")
try:
    DEFAULT_API_URL = st.secrets.get("FORECAST_API_URL", DEFAULT_API_URL)
except Exception:
    pass
DEFAULT_API_URL = DEFAULT_API_URL.rstrip("/")
st.set_page_config(page_title="Daily Revenue Forecast", page_icon="📈", layout="wide")

st.title("Daily Revenue Forecast")
st.caption("Historical daily wholesale revenue and recursive Tuned Ridge forecasts.")

with st.sidebar:
    st.header("Forecast controls")
    horizon = st.radio(
        "Forecast horizon (days)",
        options=[30, 60, 90],
        index=2,
        horizontal=True,
        help="Select the forecast period: 30, 60, or 90 days."
    )
    api_url = st.text_input("Backend API URL", value=DEFAULT_API_URL, help="Set FORECAST_API_URL in deployment settings.")
    st.caption("Forecasts are generated by the backend API using the exported model and historical data.")

@st.cache_data(ttl=60)
def get_json(url: str, timeout: int = 30):
    response = requests.get(url, timeout=timeout)
    response.raise_for_status()
    return response.json()

try:
    health = get_json(f"{api_url.rstrip('/')}/health")
    dashboard = get_json(f"{api_url.rstrip('/')}/api/dashboard?horizon={horizon}")
    metadata = get_json(f"{api_url.rstrip('/')}/api/metadata")
except Exception as exc:
    st.error("Could not reach the forecasting API.")
    st.write("Check that the backend is deployed and that the API URL is correct.")
    st.code(f"Current API URL: {api_url}")
    st.caption(f"Technical detail: {exc}")
    st.stop()

def money(value):
    return f"${value:,.2f}"

k1, k2, k3 = st.columns(3)
k1.metric("Total forecast revenue", money(dashboard["total_forecast_revenue"]))
k2.metric("Average daily forecast", money(dashboard["average_daily_forecast_revenue"]))
k3.metric("Forecast horizon", f'{dashboard["horizon"]} days')

st.subheader("Historical revenue and forecast")
chart_df = pd.DataFrame(dashboard["chart_data"])
chart_df["Date"] = pd.to_datetime(chart_df["Date"])
chart_df = chart_df.pivot(index="Date", columns="Series", values="Revenue").sort_index()
st.line_chart(chart_df, height=420)

left, right = st.columns([1, 1])
with left:
    st.subheader("Monthly forecast revenue")
    monthly = pd.DataFrame(dashboard["monthly_forecast"])
    if not monthly.empty:
        monthly = monthly.set_index("Month")
        st.bar_chart(monthly, height=320)
    else:
        st.info("No monthly forecast data.")
with right:
    st.subheader("Historical performance")
    a, b = st.columns(2)
    a.metric("Total historical revenue", money(dashboard["total_historical_revenue"]))
    b.metric("Average daily sales", money(dashboard["average_daily_historical_revenue"]))
    st.metric("Peak sales day", dashboard["peak_sales_date"], money(dashboard["peak_sales_revenue"]))

st.subheader("Daily forecast")
forecast_df = pd.DataFrame(dashboard["daily_forecast"])
if not forecast_df.empty:
    st.dataframe(forecast_df, use_container_width=True, hide_index=True)
    csv_bytes = forecast_df.to_csv(index=False).encode("utf-8")
    st.download_button(
        "Download forecast as CSV",
        data=csv_bytes,
        file_name=f"daily_revenue_forecast_{horizon}_days.csv",
        mime="text/csv",
    )

with st.expander("Model performance and metadata"):
    st.write(f"**Model:** {metadata['model']}")
    st.write("**Pipeline:** " + " → ".join(metadata["pipeline_steps"]))
    c1, c2, c3 = st.columns(3)
    c1.metric("Test MAE", money(metadata["test_mae"]))
    c2.metric("Test RMSE", money(metadata["test_rmse"]))
    c3.metric("Test R²", f'{metadata["test_r2"]:.3f}')
    st.write(f"**Input features ({metadata['feature_count']}):** " + ", ".join(metadata["features"]))
    st.write(f"**Historical range:** {metadata['history_start']} to {metadata['history_end']}")

st.caption(
    f"Data range: {dashboard['history_start']} – {dashboard['history_end']} | "
    f"Forecast: {dashboard['forecast_start']} – {dashboard['forecast_end']} | "
    f"API status: {health['status']}"
)
